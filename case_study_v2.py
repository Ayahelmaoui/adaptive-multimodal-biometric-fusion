"""### 1. Parameters and scenarios

S4 is the primary scenario. Periocular availability is fixed at 0.90; face availability and quality distribution vary by scenario
"""

A_F, A_P = 0.90, 0.85
CHANCE = 0.02
BETA_HIGH, BETA_LOW = (5, 1), (1, 2)
Z95 = 1.96

N = 50_000
P_AVAIL_P = 0.90
TAU_DEFAULT, SIGMA_DEFAULT = 0.30, 0.15
CONDS = ("C1", "C2", "C3", "C4", "C5")
SCENARIOS = {
    "S4": dict(p_avail_f=0.60, beta=BETA_LOW,  seed=44),  # primary
    "S1": dict(p_avail_f=0.95, beta=BETA_HIGH, seed=41),
    "S2": dict(p_avail_f=0.95, beta=BETA_LOW,  seed=42),
    "S3": dict(p_avail_f=0.60, beta=BETA_HIGH, seed=43),
}
SCENARIO_ORDER = ["S1", "S2", "S3", "S4"]
print(f"N={N:,} trials/scenario | tau={TAU_DEFAULT} | sigma={SIGMA_DEFAULT}")

"""### 2. Simulation functions

generate_trials creates shared trial draws. A Gaussian copula is used when rho is nonzero, preserving the Beta marginal distributions while inducing quality correlation.
"""

def pc(a, q):
    return a * q + CHANCE * (1 - q)

def g(r):
    """Reliability transform; identity in this case study."""
    return r

def generate_trials(n, p_avail_f, p_avail_p, beta_params, seed, rho=0.0):
    rng = np.random.default_rng(seed)
    avail_f = rng.random(n) < p_avail_f
    avail_p = rng.random(n) < p_avail_p
    a_b, b_b = beta_params
    q_f, q_p = rng.beta(a_b, b_b, n), rng.beta(a_b, b_b, n)
    z_f, z_p = rng.normal(0, 1, n), rng.normal(0, 1, n)

    if rho != 0.0:
        # Separate stream: rho=0 random draws remain unchanged.
        rng2 = np.random.default_rng(seed + 1000)
        u1 = rng2.standard_normal(n)
        u2 = rho * u1 + np.sqrt(1 - rho**2) * rng2.standard_normal(n)
        q_f = beta_dist.ppf(norm.cdf(u1), a_b, b_b)
        q_p = beta_dist.ppf(norm.cdf(u2), a_b, b_b)

    return dict(avail_f=avail_f, avail_p=avail_p,
                q_f=q_f, q_p=q_p, z_f=z_f, z_p=z_p)

def weighted_result(pcf, pcp, mask_f, mask_p, wf_raw, wp_raw):
    denom = wf_raw + wp_raw
    any_avail = mask_f | mask_p
    degenerate = any_avail & (denom == 0)
    # Zero-sum tie-break: equal weights across available modalities.
    wf = np.where(degenerate, np.where(mask_f, 1.0, 0.0), wf_raw)
    wp = np.where(degenerate, np.where(mask_p, 1.0, 0.0), wp_raw)
    denom2 = wf + wp
    empty = (~any_avail) | (denom2 == 0)

    corr = np.where(
        empty, 0.0,
        (wf * pcf + wp * pcp) / np.where(denom2 == 0, 1e-9, denom2)
    )
    n_trials = len(corr)
    n_answered = max(empty.size - empty.sum(), 1)
    coverage = 1 - empty.mean()

    return dict(
        corr=corr,
        correct=corr.mean(),
        abst=empty.mean(),
        coverage=coverage,
        acc_answered=corr.sum() / n_answered,
        half_ci=Z95 * corr.std(ddof=1) / np.sqrt(n_trials)
    )

def evaluate(t, tau, sigma):
    af, ap = t["avail_f"], t["avail_p"]
    r_f = np.clip(t["q_f"] + t["z_f"] * sigma, 0, 1)
    r_p = np.clip(t["q_p"] + t["z_p"] * sigma, 0, 1)
    pcf, pcp = pc(A_F, t["q_f"]), pc(A_P, t["q_p"])

    both = af & ap
    sel_f = np.where(af, r_f, -np.inf) > tau
    sel_p = np.where(ap, r_p, -np.inf) > tau
    one, zero = np.ones_like(r_f), np.zeros_like(r_f)

    return {
        "C1": weighted_result(pcf, pcp, both, both,
            np.where(both, one, zero), np.where(both, one, zero)),
        "C2": weighted_result(pcf, pcp, both, both,
            np.where(both, g(r_f), 0.0), np.where(both, g(r_p), 0.0)),
        "C3": weighted_result(pcf, pcp, af, ap,
            np.where(af, one, zero), np.where(ap, one, zero)),
        "C4": weighted_result(pcf, pcp, af, ap,
            np.where(af, g(r_f), 0.0), np.where(ap, g(r_p), 0.0)),
        "C5": weighted_result(pcf, pcp, sel_f, sel_p,
            np.where(sel_f, g(r_f), 0.0), np.where(sel_p, g(r_p), 0.0)),
    }

def run_experiment(rho=0.0):
    results, cache = {}, {}
    for name, cfg in SCENARIOS.items():
        trials = generate_trials(
            N, cfg["p_avail_f"], P_AVAIL_P, cfg["beta"], cfg["seed"], rho
        )
        cache[name] = trials
        results[name] = evaluate(trials, TAU_DEFAULT, SIGMA_DEFAULT)
    return results, cache

def metric_table(results, metric):
    rows = []
    for scenario in SCENARIO_ORDER:
        rows.append({
            "Scenario": scenario,
            **{cond: results[scenario][cond][metric] for cond in CONDS}
        })
    return pd.DataFrame(rows).set_index("Scenario")

"""### 3. Main experiment — independent quality (rho = 0)

The tables below keep the main outcomes separate. The 95% half-width is calculated for mean correctness across all trials, including abstentions scored as zero.
"""

results_rho0, trial_cache_rho0 = run_experiment(rho=0.0)

print("Experimental configuration")
display(pd.DataFrame([
    ("Trials per scenario", f"{N:,}"),
    ("Face correctness coefficient", A_F),
    ("Periocular correctness coefficient", A_P),
    ("Chance floor", CHANCE),
    ("Face availability", "0.95 for S1/S2; 0.60 for S3/S4"),
    ("Periocular availability", P_AVAIL_P),
    ("Selection threshold tau", TAU_DEFAULT),
    ("Estimator noise sigma", SIGMA_DEFAULT),
], columns=["Parameter", "Value"]).set_index("Parameter"))

correct_table = metric_table(results_rho0, "correct")
coverage_table = metric_table(results_rho0, "coverage")
abstention_table = metric_table(results_rho0, "abst")
answered_table = metric_table(results_rho0, "acc_answered")
ci_table = metric_table(results_rho0, "half_ci")

print("A. Correctness (abstention = 0)")
display(correct_table.style.format("{:.3f}").background_gradient(cmap="YlGn", axis=None))

print("B. Coverage")
